/** Fallback progress for students without a curated trend line. */
export function buildFallbackProgress(latestScore: number): ProgressPoint[] {
  const labels = [
    "Mar 15",
    "Mar 22",
    "Mar 29",
    "Apr 5",
    "Apr 12",
    "Apr 19",
    "Apr 26",
    "May 3",
  ];
  const start = Math.max(40, latestScore - 28);
  const step = (latestScore - start) / (labels.length - 1);
  return labels.map((date, i) => ({
    date,
    score: Math.round(start + step * i),
  }));
}

/** Fallback interview history derived from a student's latest score. */
export function buildFallbackInterviews(
  student: Student
): InterviewSession[] {
  const types = student.interviewTypes.length
    ? student.interviewTypes
    : (["Behavioral"] as const);
  return [0, 1, 2, 3].map((i) => ({
    id: `${student.id}-int-${i}`,
    studentId: student.id,
    interviewType: types[i % types.length],
    score: Math.max(45, student.latestScore - i * 4),
    status: "Completed" as const,
    feedbackSummary:
      i === 0
        ? "Most recent session. Keep building on your strengths."
        : "Completed practice session with actionable feedback.",
    completedAt: student.lastInterviewDate ?? "2025-05-01",
  }));
}
